1. W celu skorzystania z usługi świadczonej w Serwisie, Użytkownik jako Administrator danych zawartych w fakturach i dokumentach przechowywanych w Serwisie powierza Operatorowi jako Procesorowi przetwarzanie danych osobowych, a Procesor zobowiązuje się do przetwarzania powierzonych mu przez Administratora danych, danych osobowych w imieniu i na rzecz Administratora danych.

