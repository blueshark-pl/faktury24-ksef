3. Procesor oświadcza, że spełnia następujące wymogi wskazane w Wykazie środków technicznych i organizacyjnych zapewniające bezpieczeństwo powierzonych do przetwarzania danych osobowych:

3.1. Każda osoba dopuszczona do przetwarzania danych osobowych (np. pracownik Procesora) posiada upoważnienie do przetwarzania danych oraz złożyła oświadczenie o zachowaniu danych osobowych w tajemnicy.

3.2. Obszar przetwarzania danych osobowych chroniony jest przed dostępem osób nieuprawnionych (w tym w szczególności przez zamykane na klucz pomieszczenia oraz szafy, w których przechowywane są dokumenty papierowe zawierające dane osobowe).

3.3. Po zakończeniu pracy dokumenty papierowe są zabezpieczone w sposób uniemożliwiający zapoznanie się z ich treścią przez osoby nieuprawnione (np. chowane do zamykanych na klucz szaf lub szuflad, umieszczane w zamykanych na klucz pomieszczeniach).

3.4. Procesor stosuje zasadę uprawnień koniecznych, tzn. każda osoba dopuszczona do przetwarzania danych osobowych posiada dostęp wyłącznie do takiego zakresu danych, jaki jest jej niezbędny do wykonywania przez nią swoich obowiązków.

3.5. Przynajmniej raz w roku Procesor dokonuje przeglądu uprawnień dostępowych przynależnych osobom dopuszczonym do przetwarzania danych osobowych pod kątem ich niezbędności.

3.6. Każda osoba dopuszczona do przetwarzania danych osobowych w systemie informatycznym posiada indywidualne konto dostępu zapewniające rozliczalność operacji na tych danych.

3.7. Stosowane jest silne hasło dostępu do systemu informatycznego.

3.8. System regularnie wymusza zmianę hasła.

3.9. System zbiera logi systemowe dla zdarzeń związanych z logowaniem/wylogowywaniem danych oraz nadawaniem uprawnień do systemów.

3.10. W przypadku połączenia sieci lokalnej Procesora z siecią Internet, sieci te oddzielone są od siebie za pomocą Firewalla.

3.11. Stosowany jest system ochrony przed wirusami.

3.12. W przypadku zgrywania danych osobowych na dyski zewnętrzne, ich przenoszenie możliwe jest tylko po zaszyfrowaniu dysku.

3.13. Dyski, na których przechowywane są dane osobowe powinny być backupowane (wymagane odpowiednio przechowywanie kopii zapasowych w bezpiecznej odległości od lokalizacji centralnej).

3.14. Lokalne dyski twarde komputerów przenośnych są szyfrowane.

